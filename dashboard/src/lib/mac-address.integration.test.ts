import assert from "node:assert/strict";
import test from "node:test";
import { registerHooks } from "node:module";
import { mkdtempSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { randomBytes } from "node:crypto";
import bcrypt from "bcryptjs";
import { Pool } from "pg";

// node --env-file=.env.local --import tsx --test src/lib/mac-address.integration.test.ts
test("printer MAC persistence and monitoring integration", async (t) => {
  assert.ok(process.env.DATABASE_URL);
  const pool = new Pool({ connectionString: process.env.DATABASE_URL, max: 1 });
  const globals = globalThis as typeof globalThis & { __arenaNextJsPostgresqlPool?: Pool };
  globals.__arenaNextJsPostgresqlPool = pool;
  const fixtureDir = mkdtempSync(join(tmpdir(), "mac-integration-"));
  const authFixture = join(fixtureDir, "auth.cjs");
  const cacheFixture = join(fixtureDir, "cache.cjs");
  writeFileSync(authFixture, 'exports.requireModuleFullAccess = async () => ({role:"admin"}); exports.requireAdmin = async () => ({role:"admin"});');
  writeFileSync(cacheFixture, 'exports.revalidatePath = () => {};');
  const hooks = registerHooks({
    resolve(specifier, context, nextResolve) {
      const resolved = nextResolve(specifier === "server-only" ? "next/dist/compiled/server-only/empty.js" : specifier, context);
      // Supply an admin session and disable Next cache side effects for this test only.
      if (resolved.url.endsWith("/lib/server-utils.ts")) return nextResolve(authFixture, context);
      if (resolved.url.endsWith("/next/cache.js")) return nextResolve(cacheFixture, context);
      return resolved;
    },
  });
  try {
    // Session-local tables prevent writes to application data, including sequences.
    for (const table of ["printers", "monitoring_agents", "printer_monitoring_assignments", "printer_monitoring_readings", "printer_consumable_readings", "printer_alerts", "notifications", "system_settings", "printer_discovery_scans", "printer_toner_types"]) {
      await pool.query(`CREATE TEMP TABLE ${table} AS SELECT * FROM public.${table} WITH NO DATA`);
    }
    for (const table of ["printers", "printer_monitoring_readings", "printer_alerts"]) {
      await pool.query(`ALTER TABLE pg_temp.${table} ALTER COLUMN id SET NOT NULL, ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
    }
    await pool.query("ALTER TABLE pg_temp.printer_monitoring_assignments ADD PRIMARY KEY (printer_id)");
    const { createPrinterAction, updatePrinterAction } = await import("../app/(app)/printers/actions");
    const form = (entries: Record<string, string>) => {
      const data = new FormData();
      for (const [key, value] of Object.entries(entries)) data.set(key, value);
      return data;
    };
    await t.test("Add and Edit save normalized MAC addresses and reject invalid input", async () => {
      await assert.rejects(createPrinterAction({}, form({ serialNumber: "MAC-TEST", model: "Test Printer", ipAddress: "192.0.2.10", macAddress: "00-1a-2b-3c-4d-5e" })), /NEXT_REDIRECT/);
      assert.equal((await pool.query("SELECT mac_address FROM printers WHERE id = 1")).rows[0].mac_address, "00:1A:2B:3C:4D:5E");
      const invalid = await updatePrinterAction({}, form({ id: "1", macAddress: "invalid" }));
      assert.ok(invalid.fieldErrors?.macAddress);
      await assert.rejects(updatePrinterAction({}, form({ id: "1", ipAddress: "192.0.2.10", macAddress: "001a.2b3c.4d60" })), /NEXT_REDIRECT/);
      assert.equal((await pool.query("SELECT mac_address FROM printers WHERE id = 1")).rows[0].mac_address, "00:1A:2B:3C:4D:60");
      await assert.rejects(updatePrinterAction({}, form({ id: "1", ipAddress: "192.0.2.10", macAddress: "" })), /NEXT_REDIRECT/);
      assert.equal((await pool.query("SELECT mac_address FROM printers WHERE id = 1")).rows[0].mac_address, null);
    });

    const token = randomBytes(32).toString("hex");
    await pool.query("INSERT INTO monitoring_agents (id, agent_key, name, token_hash, status) VALUES (1, 'mac-test', 'MAC test', $1, 'online')", [await bcrypt.hash(token, 4)]);
    await pool.query("INSERT INTO printer_monitoring_assignments (printer_id, agent_id) VALUES (1, 1)");
    const { POST: ingest } = await import("../app/api/monitoring/ingest/route");
    const upload = (macAddress?: string, online = true) => ingest(new Request("http://localhost/api/monitoring/ingest", {
      method: "POST", headers: { "Content-Type": "application/json", Authorization: `Bearer ${token}` },
      body: JSON.stringify({ agent: { key: "mac-test", name: "MAC test" }, sentAt: new Date().toISOString(), printers: [{ name: "Test", serial: "MAC-TEST", ip: "192.0.2.10", online, macAddress }] }),
    }));
    await t.test("only online, assigned observations fill missing MAC; saved values survive later uploads", async () => {
      for (const [value, online] of [[undefined, true], ["invalid", true], ["00:1A:2B:3C:4D:5E", false]] as const) {
        assert.equal((await upload(value, online)).status, 200);
        assert.equal((await pool.query("SELECT mac_address FROM printers WHERE id = 1")).rows[0].mac_address, null);
      }
      await pool.query("UPDATE printer_monitoring_assignments SET agent_id = 2");
      assert.equal((await upload("00:1A:2B:3C:4D:5E")).status, 200);
      assert.equal((await pool.query("SELECT mac_address FROM printers WHERE id = 1")).rows[0].mac_address, null);
      await pool.query("UPDATE printer_monitoring_assignments SET agent_id = 1");
      assert.equal((await upload("00-1a-2b-3c-4d-5e")).status, 200);
      assert.equal((await pool.query("SELECT mac_address FROM printers WHERE id = 1")).rows[0].mac_address, "00:1A:2B:3C:4D:5E");
      assert.equal((await upload("00:1A:2B:3C:4D:60")).status, 200);
      assert.equal((await pool.query("SELECT mac_address FROM printers WHERE id = 1")).rows[0].mac_address, "00:1A:2B:3C:4D:5E");
      assert.equal((await pool.query("SELECT count(*)::int AS count FROM printer_monitoring_readings")).rows[0].count, 5);
    });
    await t.test("discovery saves normalized MAC for Add Printer", async () => {
      await pool.query("INSERT INTO printer_discovery_scans (id, agent_id, status) VALUES (1, 1, 'running')");
      const { POST: discovery } = await import("../app/api/monitoring/discovery/route");
      const response = await discovery(new Request("http://localhost/api/monitoring/discovery", {
        method: "POST", headers: { "Content-Type": "application/json", Authorization: `Bearer ${token}`, "x-seaoil-agent-key": "mac-test" },
        body: JSON.stringify({ jobId: 1, results: [{ ip: "192.0.2.10", macAddress: "001a2b3c4d5e" }] }),
      }));
      assert.equal(response.status, 200);
      assert.equal((await pool.query("SELECT results FROM printer_discovery_scans WHERE id = 1")).rows[0].results[0].macAddress, "00:1A:2B:3C:4D:5E");
    });
  } finally {
    hooks.deregister();
    rmSync(fixtureDir, { recursive: true, force: true });
    delete globals.__arenaNextJsPostgresqlPool;
    await pool.end();
  }
});
