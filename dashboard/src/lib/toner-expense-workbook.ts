import ExcelJS, { type Cell, type Row, type Worksheet } from "exceljs";
import type { SessionPayload } from "@/lib/auth";
import type { ExpenseBreakdown } from "@/lib/toner-expenses";
import type { TonerExpenseExportReport } from "@/lib/toner-expense-export";

const NAVY = "014171";
const BLUE = "0B70A8";
const YELLOW = "FFD100";
const PALE_BLUE = "EAF5FB";
const PALE_YELLOW = "FFF9D9";
const WHITE = "FFFFFF";
const SLATE = "475569";
const CURRENCY_FORMAT = '₱#,##0.00;[Red]-₱#,##0.00';

export async function buildTonerExpenseWorkbook(
  report: TonerExpenseExportReport,
  actor: Pick<SessionPayload, "fullName" | "email" | "username">,
  generatedAt = new Date(),
) {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = "SEAOIL PrintOps";
  workbook.company = "SEAOIL Philippines, Inc.";
  workbook.title = "Toner Expense Report";
  workbook.subject = "Estimated toner expenses based on recorded requests and current unit costs";
  workbook.created = generatedAt;
  workbook.modified = generatedAt;
  workbook.calcProperties.fullCalcOnLoad = true;

  addSummarySheet(workbook, report, actor, generatedAt);
  addDetailsSheet(workbook, report);
  addDepartmentSheet(workbook, report);
  addLocationSheet(workbook, report);
  addExportInformationSheet(workbook, report, actor, generatedAt);

  return workbook.xlsx.writeBuffer();
}

function addSummarySheet(
  workbook: ExcelJS.Workbook,
  report: TonerExpenseExportReport,
  actor: Pick<SessionPayload, "fullName" | "email" | "username">,
  generatedAt: Date,
) {
  const sheet = workbook.addWorksheet("Summary", {
    views: [{ showGridLines: false }],
    properties: { tabColor: { argb: NAVY } },
  });
  sheet.columns = [
    { key: "label", width: 29 },
    { key: "value", width: 44 },
    { key: "extra", width: 28 },
  ];
  titleBlock(sheet, "Toner Expense Report", "Management summary of recorded toner requests");

  let rowNumber = 5;
  sectionTitle(sheet, rowNumber++, "Report filters", 3);
  const filterRows = [
    ["Period", report.filterLabels.period],
    ["Department", report.filterLabels.department],
    ["Location", report.filterLabels.location],
    ["Toner type", report.filterLabels.tonerType],
    ["ITS name", report.filterLabels.itsName],
  ];
  for (const values of filterRows) {
    const row = sheet.getRow(rowNumber++);
    row.values = values;
    styleLabelValueRow(row);
  }

  rowNumber += 1;
  sectionTitle(sheet, rowNumber++, "Selected results", 3);
  const priceCoverage = report.summary.requestLines
    ? report.summary.pricedRequestLines / report.summary.requestLines
    : 0;
  const metrics: Array<[string, string | number, string?]> = [
    ["Estimated expense", report.summary.totalExpenseCents / 100, "Based on current unit costs"],
    ["Units requested", report.summary.totalUnits],
    ["Request records", report.summary.requestLines],
    ["Price coverage", priceCoverage, `${report.summary.pricedRequestLines} of ${report.summary.requestLines} records priced`],
  ];
  metrics.forEach(([label, value, extra], index) => {
    const row = sheet.getRow(rowNumber++);
    row.values = [label, value, extra ?? ""];
    styleLabelValueRow(row);
    row.getCell(2).font = { bold: true, color: { argb: NAVY }, size: 12 };
    if (index === 0) row.getCell(2).numFmt = CURRENCY_FORMAT;
    if (index === 3) row.getCell(2).numFmt = "0%";
  });

  rowNumber += 1;
  sectionTitle(sheet, rowNumber++, "Important methodology note", 3, YELLOW, NAVY);
  sheet.mergeCells(rowNumber, 1, rowNumber + 2, 3);
  const noteCell = sheet.getCell(rowNumber, 1);
  noteCell.value = "Expense figures are estimates calculated as requested quantity × the toner type's current unit cost. Updating a unit cost recalculates historical estimates; transaction records are not changed.";
  noteCell.alignment = { vertical: "middle", horizontal: "left", wrapText: true };
  noteCell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: PALE_YELLOW } };
  noteCell.font = { color: { argb: SLATE }, size: 10 };
  noteCell.border = thinBorder("F1D66A");
  sheet.getRow(rowNumber).height = 24;
  sheet.getRow(rowNumber + 1).height = 24;
  sheet.getRow(rowNumber + 2).height = 24;

  sheet.headerFooter.oddFooter = `Generated by ${actor.fullName || actor.username} on ${formatManilaDateTime(generatedAt)} | Page &P of &N`;
  sheet.pageSetup = { orientation: "portrait", fitToPage: true, fitToWidth: 1, fitToHeight: 0 };
}

function addDetailsSheet(workbook: ExcelJS.Workbook, report: TonerExpenseExportReport) {
  const sheet = workbook.addWorksheet("Expense Details", {
    views: [{ state: "frozen", ySplit: 1, showGridLines: false }],
    properties: { tabColor: { argb: BLUE } },
  });
  sheet.columns = [
    { header: "Transaction ID", key: "transactionId", width: 15 },
    { header: "Group ID", key: "groupId", width: 22 },
    { header: "Date", key: "date", width: 13 },
    { header: "Ticket Reference", key: "ticketReference", width: 20 },
    { header: "Department", key: "department", width: 27 },
    { header: "Location", key: "location", width: 27 },
    { header: "Toner Type", key: "tonerType", width: 24 },
    { header: "Quantity", key: "quantity", width: 12 },
    { header: "Unit Cost (PHP)", key: "unitCost", width: 18 },
    { header: "Total Expense (PHP)", key: "totalExpense", width: 21 },
    { header: "ITS Name", key: "itsName", width: 22 },
    { header: "Remarks", key: "remarks", width: 34 },
    { header: "Recorded At", key: "recordedAt", width: 22 },
  ];
  styleTableHeader(sheet.getRow(1));

  for (const expense of report.rows) {
    const row = sheet.addRow({
      transactionId: expense.transactionId,
      groupId: expense.groupId,
      date: expense.date,
      ticketReference: expense.ticketReference,
      department: expense.department,
      location: expense.location,
      tonerType: expense.tonerType,
      quantity: expense.quantity,
      unitCost: expense.unitCostCents / 100,
      totalExpense: expense.totalExpenseCents / 100,
      itsName: expense.itsName,
      remarks: expense.remarks,
      recordedAt: expense.recordedAt,
    });
    row.getCell(9).numFmt = CURRENCY_FORMAT;
    row.getCell(10).numFmt = CURRENCY_FORMAT;
    row.getCell(13).numFmt = "dd mmm yyyy hh:mm";
    styleDataRow(row);
  }

  sheet.autoFilter = { from: "A1", to: "M1" };
  sheet.getColumn(8).alignment = { horizontal: "right" };
  sheet.getColumn(9).alignment = { horizontal: "right" };
  sheet.getColumn(10).alignment = { horizontal: "right" };
  sheet.pageSetup = { orientation: "landscape", fitToPage: true, fitToWidth: 1, fitToHeight: 0 };
  sheet.headerFooter.oddFooter = "SEAOIL PrintOps toner expense details | Page &P of &N";
}

function addDepartmentSheet(workbook: ExcelJS.Workbook, report: TonerExpenseExportReport) {
  const sheet = workbook.addWorksheet("Department Breakdown", {
    views: [{ state: "frozen", ySplit: 1, showGridLines: false }],
    properties: { tabColor: { argb: "7C3AED" } },
  });
  sheet.columns = [
    { header: "Department", key: "name", width: 34 },
    { header: "Request Records", key: "requestLines", width: 18 },
    { header: "Units", key: "units", width: 13 },
    { header: "Top Toner", key: "topToner", width: 27 },
    { header: "Expense (PHP)", key: "expense", width: 19 },
    { header: "Share", key: "share", width: 13 },
  ];
  styleTableHeader(sheet.getRow(1));
  report.summary.departments.forEach((item) => {
    const row = sheet.addRow({
      ...breakdownValues(item, report.summary.totalExpenseCents),
      topToner: item.topToner,
    });
    styleBreakdownRow(row, 5, 6);
  });
  sheet.autoFilter = { from: "A1", to: "F1" };
  sheet.pageSetup = { orientation: "landscape", fitToPage: true, fitToWidth: 1, fitToHeight: 0 };
}

function addLocationSheet(workbook: ExcelJS.Workbook, report: TonerExpenseExportReport) {
  const sheet = workbook.addWorksheet("Location Breakdown", {
    views: [{ state: "frozen", ySplit: 1, showGridLines: false }],
    properties: { tabColor: { argb: "0F766E" } },
  });
  sheet.columns = [
    { header: "Location", key: "name", width: 36 },
    { header: "Request Records", key: "requestLines", width: 18 },
    { header: "Units", key: "units", width: 13 },
    { header: "Expense (PHP)", key: "expense", width: 19 },
    { header: "Share", key: "share", width: 13 },
  ];
  styleTableHeader(sheet.getRow(1));
  report.summary.locations.forEach((item) => {
    const row = sheet.addRow(breakdownValues(item, report.summary.totalExpenseCents));
    styleBreakdownRow(row, 4, 5);
  });
  sheet.autoFilter = { from: "A1", to: "E1" };
  sheet.pageSetup = { orientation: "landscape", fitToPage: true, fitToWidth: 1, fitToHeight: 0 };
}

function addExportInformationSheet(
  workbook: ExcelJS.Workbook,
  report: TonerExpenseExportReport,
  actor: Pick<SessionPayload, "fullName" | "email" | "username">,
  generatedAt: Date,
) {
  const sheet = workbook.addWorksheet("Export Information", {
    views: [{ showGridLines: false }],
    properties: { tabColor: { argb: YELLOW } },
  });
  sheet.columns = [{ width: 29 }, { width: 76 }];
  titleBlock(sheet, "Export Information", "Traceability, filters, and calculation method", 2);
  sectionTitle(sheet, 5, "Export details", 2);
  const rows: Array<[string, string | number]> = [
    ["Generated by", actor.fullName || actor.username],
    ["Account email", actor.email],
    ["Generated at", `${formatManilaDateTime(generatedAt)} (Asia/Manila)`],
    ["Exported request records", report.summary.requestLines],
    ["Maximum export size", "50,000 request records"],
    ["Period", report.filterLabels.period],
    ["Department", report.filterLabels.department],
    ["Location", report.filterLabels.location],
    ["Toner type", report.filterLabels.tonerType],
    ["ITS name", report.filterLabels.itsName],
    ["Calculation", "Requested quantity × current toner type unit cost"],
    ["Historical treatment", "If a current unit cost changes, historical estimates are recalculated; transaction records remain unchanged."],
    ["Price coverage", `${report.summary.pricedRequestLines} of ${report.summary.requestLines} request records have a positive unit cost.`],
    ["Unpriced toner types", report.summary.unpricedTonerTypes.join(", ") || "None"],
    ["Classification", "For internal SEAOIL use only"],
  ];
  rows.forEach((values, index) => {
    const row = sheet.getRow(index + 6);
    row.values = values;
    styleLabelValueRow(row);
    row.getCell(2).alignment = { vertical: "top", wrapText: true };
    if (index === 11 || index === 12) row.height = 34;
  });
  sheet.pageSetup = { orientation: "portrait", fitToPage: true, fitToWidth: 1, fitToHeight: 0 };
}

function breakdownValues(item: ExpenseBreakdown, totalExpenseCents: number) {
  return {
    name: item.name,
    requestLines: item.requestLines,
    units: item.units,
    expense: item.expenseCents / 100,
    share: totalExpenseCents ? item.expenseCents / totalExpenseCents : 0,
  };
}

function titleBlock(sheet: Worksheet, title: string, subtitle: string, columnCount = 3) {
  sheet.mergeCells(1, 1, 1, columnCount);
  const titleCell = sheet.getCell(1, 1);
  titleCell.value = title;
  titleCell.font = { size: 20, bold: true, color: { argb: WHITE } };
  titleCell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: NAVY } };
  titleCell.alignment = { vertical: "middle" };
  sheet.getRow(1).height = 34;
  sheet.mergeCells(2, 1, 2, columnCount);
  const subtitleCell = sheet.getCell(2, 1);
  subtitleCell.value = subtitle;
  subtitleCell.font = { size: 10, bold: true, color: { argb: NAVY } };
  subtitleCell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: YELLOW } };
  subtitleCell.alignment = { vertical: "middle" };
  sheet.getRow(2).height = 24;
}

function sectionTitle(
  sheet: Worksheet,
  rowNumber: number,
  title: string,
  columnCount: number,
  background = BLUE,
  foreground = WHITE,
) {
  sheet.mergeCells(rowNumber, 1, rowNumber, columnCount);
  const cell = sheet.getCell(rowNumber, 1);
  cell.value = title;
  cell.font = { bold: true, color: { argb: foreground }, size: 11 };
  cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: background } };
  cell.alignment = { vertical: "middle" };
  sheet.getRow(rowNumber).height = 23;
}

function styleTableHeader(row: Row) {
  row.height = 26;
  row.eachCell((cell) => {
    cell.font = { bold: true, color: { argb: WHITE }, size: 10 };
    cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: NAVY } };
    cell.alignment = { vertical: "middle", horizontal: "center", wrapText: true };
    cell.border = thinBorder("FFFFFF");
  });
}

function styleDataRow(row: Row) {
  row.height = 21;
  row.eachCell((cell, columnNumber) => {
    cell.alignment = {
      vertical: "top",
      wrapText: [4, 5, 6, 7, 11, 12].includes(columnNumber),
      horizontal: [1, 8, 9, 10].includes(columnNumber) ? "right" : "left",
    };
    cell.border = { bottom: { style: "hair", color: { argb: "CBD5E1" } } };
    if (row.number % 2 === 0) {
      cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "F8FAFC" } };
    }
  });
}

function styleBreakdownRow(row: Row, currencyColumn: number, shareColumn: number) {
  styleDataRow(row);
  row.getCell(currencyColumn).numFmt = CURRENCY_FORMAT;
  row.getCell(shareColumn).numFmt = "0.0%";
  row.getCell(currencyColumn).font = { bold: true, color: { argb: NAVY } };
}

function styleLabelValueRow(row: Row) {
  row.getCell(1).font = { bold: true, color: { argb: NAVY } };
  row.getCell(1).fill = { type: "pattern", pattern: "solid", fgColor: { argb: PALE_BLUE } };
  row.eachCell((cell) => {
    cell.alignment = { vertical: "middle", wrapText: true };
    cell.border = thinBorder("DCE6EF");
  });
  row.height = 23;
}

function thinBorder(color: string): Partial<Cell["border"]> {
  const side = { style: "thin" as const, color: { argb: color } };
  return { top: side, left: side, bottom: side, right: side };
}

function formatManilaDateTime(value: Date) {
  return new Intl.DateTimeFormat("en-PH", {
    dateStyle: "medium",
    timeStyle: "short",
    timeZone: "Asia/Manila",
  }).format(value);
}
